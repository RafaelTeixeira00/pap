function language_selector()
{
    $currentLanguage = app_language();
    $portugueseSelected = $currentLanguage === 'pt' ? ' selected' : '';
    $englishSelected = $currentLanguage === 'en' ? ' selected' : '';

    return '<form class="language-switch" method="get">'
        . '<label class="visually-hidden" for="site-language">' . t('Idioma') . '</label>'
        . '<select id="site-language" name="lang" aria-label="' . t('Idioma') . '">'
        . '<option value="pt"' . $portugueseSelected . '>' . t('Português') . '</option>'
        . '<option value="en"' . $englishSelected . '>' . t('Inglês') . '</option>'
        . '<option value="es"' . ($currentLanguage === 'es' ? ' selected' : '') . '>Español</option>'
        . '<option value="fr"' . ($currentLanguage === 'fr' ? ' selected' : '') . '>Français</option>'
        . '</select><button type="submit">' . t('Aplicar') . '</button></form>';
}
