$supportedLanguages = ['pt', 'en', 'es', 'fr'];
$requestedLanguage = $_GET['lang'] ?? null;
if (is_string($requestedLanguage) && in_array($requestedLanguage, $supportedLanguages, true)) {
    $_SESSION['site_language'] = $requestedLanguage;
}

function app_language()
{
    $language = $_SESSION['site_language'] ?? 'pt';

    return in_array($language, ['pt', 'en', 'es', 'fr'], true) ? $language : 'pt';
}

function app_language_tag()
{
    $languageTags = [
        'pt' => 'pt-PT',
        'en' => 'en',
        'es' => 'es',
        'fr' => 'fr',
    ];

    return $languageTags[app_language()];
}

